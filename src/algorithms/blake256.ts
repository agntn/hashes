/**
 * Hashes a message with BLAKE-256. The padding is SHA-256's closed by a set bit before the
 * length, and a block holding padding alone is hashed under a zero counter.
 *
 * @param message - Bytes to hash.
 * @returns {Uint8Array} The 32-byte digest.
 */
export function blake256(message: Uint8Array): Uint8Array {
  const padded = new Uint8Array(Math.ceil((message.length + 9) / 64) * 64);
  padded.set(message);
  const last = padded.length - 9;
  padded[message.length] = 0x80;
  padded[last] = last === message.length ? 0x81 : 0x01;
  const view = new DataView(padded.buffer);
  const bits = message.length * 8;
  view.setUint32(padded.length - 8, Math.floor(bits / 0x1_0000_0000));
  view.setUint32(padded.length - 4, bits >>> 0);

  const state = INITIAL.slice();
  const words = new Uint32Array(16);
  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let word = 0; word < 16; word++) words[word] = view.getUint32(offset + word * 4);
    const counted = offset < message.length ? Math.min(offset + 64, message.length) * 8 : 0;
    compress(state, words, counted >>> 0, Math.floor(counted / 0x1_0000_0000));
  }

  const digest = new Uint8Array(32);
  const out = new DataView(digest.buffer);
  for (let word = 0; word < 8; word++) out.setUint32(word * 4, state[word]!);
  return digest;
}

